        const MONTH_ABBREVIATIONS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

        function renderCardPhenology(months) {
            const activeMonths = new Set(months);
            const monthLabels = MONTH_ABBREVIATIONS.map((month, index) => {
                const active = activeMonths.has(index + 1);
                return `<span class="${active ? 'month-active' : ''}" title="${month}">${month}</span>`;
            }).join('');
            return `
                <div class="flight-season" aria-label="Typical flight season">
                    <span class="flight-label">Best viewing months</span>
                    <div class="flight-month-grid">${monthLabels}</div>
                </div>
            `;
        }

        function renderModalPhenology(months) {
            const activeMonths = new Set(months);
            return MONTH_ABBREVIATIONS.map((month, index) => {
                const active = activeMonths.has(index + 1);
                return `<span class="${active ? 'month-active' : ''}" title="${month}">${month}</span>`;
            }).join('');
        }

        function renderButterflyPhoto(container, butterfly, uid) {
            const photo = document.createElement('img');
            photo.src = butterfly.image;
            photo.alt = `${butterfly.commonName} (${butterfly.scientificName})`;
            photo.className = `photo-artwork ${uid === 'hero' ? 'hero-photo' : uid === 'modal' ? 'modal-photo' : 'specimen-photo'}`;
            photo.loading = 'lazy';
            photo.decoding = 'async';
            photo.addEventListener('error', () => {
                container.innerHTML = createButterflySVG(butterfly.id, uid);
            }, { once: true });
            container.replaceChildren(photo);
        }

        function setPhotoAttribution(container, butterfly) {
            const photoCredit = container.querySelector('[data-photo-credit]');
            const licenseCredit = container.querySelector('[data-photo-license]');

            photoCredit.href = butterfly.imageSource;
            photoCredit.textContent = `Reference photo by ${butterfly.imageCredit}`;
            licenseCredit.href = butterfly.imageLicenseUrl;
            licenseCredit.textContent = butterfly.imageLicense;

            container.querySelectorAll('a').forEach(link => {
                link.target = '_blank';
                link.rel = 'noopener noreferrer';
                link.addEventListener('click', event => event.stopPropagation());
            });
        }

